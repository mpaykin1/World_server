const fs=require('fs'),path=require('path');
const root=process.cwd();
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const policy=JSON.parse(read('data/user-link-delivery-policy.json'));
const fail=m=>{console.error('USER LINK DELIVERY FAIL:',m);process.exitCode=1;};
const ok=m=>console.log('USER LINK DELIVERY OK:',m);
const r=policy.rules||{};
if(policy.mode!=='hard-block'||r.unverifiedLink!=='HARD_BLOCK')fail('unverified links must hard-block');
if(r.freshVerificationRequired!==true||!(r.maxEvidenceAgeSeconds>0&&r.maxEvidenceAgeSeconds<=120))fail('fresh evidence <=120s required');
if(r.ephemeralPreviewMayBeFinal!==false||r.preferStableProductionUrl!==true)fail('stable production must be preferred; preview cannot be final');
if(r.requireHttp2xx!==true||r.requireApplicationReadyPredicate!==true||r.requireBrowserVerificationForPlayableWorld!==true)fail('live behavioral verification contract incomplete');
const agents=read('AGENTS.md').toLowerCase();
for(const phrase of ['verified link delivery','unverified_link','site not found'])if(!agents.includes(phrase))fail(`AGENTS.md missing ${phrase}`);
const ci=read('.github/workflows/ci.yml');
if(!ci.includes('User-facing verified-link policy (hard)')||!ci.includes('check-user-link-delivery-policy.js'))fail('CI hard link gate missing');
const runtime=read('shared/ai3d-playable-runtime.js');
if(!runtime.includes('goldenLookPad')||!runtime.includes('goldenLookKnob'))fail('AI3D visible LOOK joystick missing');
if(process.exitCode)process.exit(process.exitCode);
ok('fresh stable link + visible dual-joystick contract');
