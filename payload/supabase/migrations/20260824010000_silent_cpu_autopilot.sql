alter table public.quality_improvement_memory enable row level security;
alter table public.quality_learning_events enable row level security;
alter table public.quality_nightly_runs enable row level security;

create or replace function public.claim_quality_autopilot_job(p_worker text,p_max_cpu_seconds integer default 3600)
returns setof public.quality_autopilot_queue
language plpgsql security definer set search_path=public as $$
declare v_id bigint;
begin
  select id into v_id from public.quality_autopilot_queue
  where status='queued' and run_after<=now()
    and requires_gpu=false and estimated_paid_cost<=0
    and estimated_cpu_seconds<=greatest(1,p_max_cpu_seconds)
  order by priority desc,created_at asc
  for update skip locked limit 1;
  if v_id is null then return; end if;
  update public.quality_autopilot_queue
  set status='running',locked_by=p_worker,locked_at=now(),attempts=attempts+1
  where id=v_id;
  return query select * from public.quality_autopilot_queue where id=v_id;
end;
$$;
