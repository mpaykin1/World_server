-- V11 Silent CPU Quality Autopilot
create table if not exists public.quality_projects (
  project_key text primary key,
  enabled boolean not null default true,
  autopilot_mode text not null default 'candidate_autoimprove',
  user_priority integer not null default 50,
  current_quality numeric not null default 0,
  target_quality numeric not null default 80,
  activity_score numeric not null default 0,
  release_blockers integer not null default 0,
  last_improved_at timestamptz,
  last_scanned_at timestamptz,
  metadata jsonb not null default '{}'::jsonb
);

create table if not exists public.quality_autopilot_queue (
  id bigint generated by default as identity primary key,
  project_key text not null references public.quality_projects(project_key) on delete cascade,
  task_kind text not null,
  task_payload jsonb not null default '{}'::jsonb,
  status text not null default 'queued',
  priority numeric not null default 0,
  estimated_cpu_seconds integer not null default 60,
  estimated_paid_cost numeric not null default 0,
  requires_gpu boolean not null default false,
  attempts integer not null default 0,
  run_after timestamptz not null default now(),
  locked_by text,
  locked_at timestamptz,
  created_at timestamptz not null default now(),
  finished_at timestamptz,
  result jsonb
);
create index if not exists quality_autopilot_queue_claim_idx
  on public.quality_autopilot_queue(status, run_after, priority desc, id);

create table if not exists public.quality_improvement_memory (
  fingerprint text primary key,
  project_key text,
  action_kind text not null,
  system_area text,
  attempts integer not null default 0,
  successes integer not null default 0,
  failures integer not null default 0,
  cumulative_delta numeric not null default 0,
  average_delta numeric not null default 0,
  never_retry boolean not null default false,
  last_failure_reason text,
  last_outcome jsonb,
  updated_at timestamptz not null default now()
